const STORE = 'c2b-ask-ai';
const API = '/api/ask';

// ---- Güvenli, küçük bir Markdown dönüştürücü ----
function esc(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
function inline(s) {
  return esc(s)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\[([^\]]+)\]\(((?:https?:\/\/|\/)[^)\s]*)\)/g, (_, t, u) => {
      const ext = /^https?:\/\//.test(u) && !u.startsWith('https://docs.cloud2biz.com');
      return `<a href="${u}"${ext ? ' target="_blank" rel="noopener noreferrer"' : ''}>${t}</a>`;
    });
}
function markdown(src) {
  const out = [];
  const blocks = src.split(/```/);
  blocks.forEach((block, bi) => {
    if (bi % 2 === 1) {
      out.push(`<pre><code>${esc(block.replace(/^[\w-]*\n/, ''))}</code></pre>`);
      return;
    }
    let list = null;
    const flush = () => {
      if (list) out.push(`<${list.tag}>${list.items.map((i) => `<li>${inline(i)}</li>`).join('')}</${list.tag}>`);
      list = null;
    };
    let para = [];
    const flushPara = () => {
      if (para.length) out.push(`<p>${para.map(inline).join('<br/>')}</p>`);
      para = [];
    };
    for (const raw of block.split('\n')) {
      const line = raw.trimEnd();
      const ul = line.match(/^\s*[-*]\s+(.*)$/);
      const ol = line.match(/^\s*\d+[.)]\s+(.*)$/);
      const h = line.match(/^#{1,6}\s+(.*)$/);
      if (ul || ol) {
        flushPara();
        const tag = ul ? 'ul' : 'ol';
        if (!list || list.tag !== tag) {
          flush();
          list = {tag, items: []};
        }
        list.items.push((ul || ol)[1]);
      } else if (!line.trim()) {
        flush();
        flushPara();
      } else if (h) {
        flush();
        flushPara();
        out.push(`<p><strong>${inline(h[1])}</strong></p>`);
      } else {
        flush();
        para.push(line);
      }
    }
    flush();
    flushPara();
  });
  return out.join('');
}

function load() {
  try {
    const v = JSON.parse(sessionStorage.getItem(STORE) || '[]');
    return Array.isArray(v) ? v : [];
  } catch {
    return [];
  }
}
function save(v) {
  try {
    sessionStorage.setItem(STORE, JSON.stringify(v.slice(-20)));
  } catch {
    /* depolama yoksa önemli değil */
  }
}

function Logo() {
  return (
    <svg viewBox="0 0 32 32" width="26" height="26" aria-hidden="true">
      <defs>
        <linearGradient id="c2b-ai" x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" stopColor="#ffb08f" />
          <stop offset="1" stopColor="#f26b3a" />
        </linearGradient>
      </defs>
      <path d="M9 24a6 6 0 0 1-.6-11.97A8 8 0 0 1 23.6 10.5 5.5 5.5 0 0 1 23 24Z" fill="url(#c2b-ai)" />
      <path d="M16 12.5l1.1 2.9 2.9 1.1-2.9 1.1L16 20.5l-1.1-2.9-2.9-1.1 2.9-1.1Z" fill="#fff" />
    </svg>
  );
}

export default function AskAI() {
  const {i18n} = useDocusaurusContext();
  const locale = i18n.currentLocale === 'en' ? 'en' : 'tr';
  const t = T[locale];

  const [available, setAvailable] = useState(false);
  const [open, setOpen] = useState(false);
  const [wide, setWide] = useState(false);
  const [messages, setMessages] = useState([]);
  const [input, setInput] = useState('');
  const [busy, setBusy] = useState(false);
  const listRef = useRef(null);
  const inputRef = useRef(null);
  const abortRef = useRef(null);

  // Servis çalışıyor mu?
  useEffect(() => {
    let alive = true;
    fetch(`${API}/health`)
      .then((r) => r.ok && r.json())
      .then((j) => alive && setAvailable(!!(j && j.ok)))
      .catch(() => {});
    setMessages(load());
    try {
      if (sessionStorage.getItem(STORE + '-open') === '1') setOpen(true);
    } catch {
      /* yoksay */
    }
    return () => {
      alive = false;
    };
  }, []);

  useEffect(() => {
    try {
      sessionStorage.setItem(STORE + '-open', open ? '1' : '0');
    } catch {
      /* yoksay */
    }
    if (open && window.matchMedia('(min-width: 577px)').matches) setTimeout(() => inputRef.current?.focus(), 50);
  }, [open]);

  useEffect(() => {
    const el = listRef.current;
    if (el) el.scrollTop = el.scrollHeight;
  }, [messages, open]);

  useEffect(() => {
    const onKey = (e) => e.key === 'Escape' && setOpen(false);
    document.addEventListener('keydown', onKey);
    return () => document.removeEventListener('keydown', onKey);
  }, []);

  const ask = async (text) => {
    const q = text.trim();
    if (!q || busy) return;
    const history = [...messages.filter((m) => !m.error), {role: 'user', content: q}];
    setMessages([...history, {role: 'assistant', content: ''}]);
    setInput('');
    setBusy(true);
    const ctrl = new AbortController();
    abortRef.current = ctrl;
    let answer = '';
    try {
      const r = await fetch(API, {
        method: 'POST',
        headers: {'content-type': 'application/json'},
        body: JSON.stringify({locale, messages: history.slice(-10).map(({role, content}) => ({role, content}))}),
        signal: ctrl.signal,
      });
      if (!r.ok || !r.body) {
        const j = await r.json().catch(() => null);
        throw new Error(j?.error || t.error);
      }
      const reader = r.body.getReader();
      const dec = new TextDecoder();
      for (;;) {
        const {done, value} = await reader.read();
        if (done) break;
        answer += dec.decode(value, {stream: true});
        setMessages([...history, {role: 'assistant', content: answer}]);
      }
      if (!answer.trim()) throw new Error(t.error);
      const final = [...history, {role: 'assistant', content: answer}];
      setMessages(final);
      save(final);
    } catch (e) {
      if (e.name === 'AbortError') return;
      const final = [...history, {role: 'assistant', content: e.message || t.error, error: true}];
      setMessages(final);
      save(history);
    } finally {
      setBusy(false);
      abortRef.current = null;
    }
  };

  const reset = () => {
    abortRef.current?.abort();
    setBusy(false);
    setMessages([]);
    save([]);
    inputRef.current?.focus();
  };

  if (!available) return null;

  return (
    <>
      {!open && (
        <button type="button" className={`${styles.fab} c2b-askai-fab`} onClick={() => setOpen(true)}>
          <Logo />
          <span>{t.button}</span>
        </button>
      )}

      {open && (
        <div className={`${styles.panel} ${wide ? styles.wide : ''}`} role="dialog" aria-label={t.title}>
          <div className={styles.header}>
            <Logo />
            <strong>{t.title}</strong>
            <span className={styles.spacer} />
            {messages.length > 0 && (
              <button type="button" className={styles.iconBtn} onClick={reset} title={t.reset} aria-label={t.reset}>
                <svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true">
                  <path fill="currentColor" d="M12 5V2L7 6l5 4V7a5 5 0 1 1-5 5H5a7 7 0 1 0 7-7Z" />
                </svg>
              </button>
            )}
            <button
              type="button"
              className={`${styles.iconBtn} ${styles.hideMobile}`}
              onClick={() => setWide((w) => !w)}
              title={wide ? t.shrink : t.expand}
              aria-label={wide ? t.shrink : t.expand}>
              <svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true">
                <path
                  fill="currentColor"
                  d={wide ? 'M9 9H4V7h3V4h2v5Zm6 0V4h2v3h3v2h-5Zm-6 6v5H7v-3H4v-2h5Zm6 0h5v2h-3v3h-2v-5Z' : 'M4 4h6v2H6v4H4V4Zm10 0h6v6h-2V6h-4V4ZM4 14h2v4h4v2H4v-6Zm14 0h2v6h-6v-2h4v-4Z'}
                />
              </svg>
            </button>
            <button type="button" className={styles.iconBtn} onClick={() => setOpen(false)} title={t.close} aria-label={t.close}>
              <svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true">
                <path fill="currentColor" d="M6.4 5 12 10.6 17.6 5 19 6.4 13.4 12l5.6 5.6-1.4 1.4-5.6-5.6L6.4 19 5 17.6l5.6-5.6L5 6.4Z" />
              </svg>
            </button>
          </div>

          <div className={styles.list} ref={listRef}>
            <div className={`${styles.msg} ${styles.bot}`}>{t.hello}</div>
            {messages.length === 0 && (
              <div className={styles.examples}>
                {t.examples.map((ex) => (
                  <button key={ex} type="button" onClick={() => ask(ex)}>
                    {ex}
                  </button>
                ))}
              </div>
            )}
            {messages.map((m, i) =>
              m.role === 'user' ? (
                <div key={i} className={`${styles.msg} ${styles.user}`}>
                  {m.content}
                </div>
              ) : m.content ? (
                <div
                  key={i}
                  className={`${styles.msg} ${styles.bot} ${m.error ? styles.err : ''}`}
                  dangerouslySetInnerHTML={{__html: markdown(m.content)}}
                />
              ) : (
                <div key={i} className={`${styles.msg} ${styles.bot} ${styles.typing}`} aria-label="…">
                  <span />
                  <span />
                  <span />
                </div>
              ),
            )}
          </div>

          <form
            className={styles.form}
            onSubmit={(e) => {
              e.preventDefault();
              ask(input);
            }}>
            <textarea
              ref={inputRef}
              rows={1}
              value={input}
              maxLength={1500}
              placeholder={t.placeholder}
              onChange={(e) => setInput(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === 'Enter' && !e.shiftKey) {
                  e.preventDefault();
                  ask(input);
                }
              }}
            />
            <button type="submit" disabled={busy || !input.trim()} aria-label={t.send} title={t.send}>
              <svg viewBox="0 0 24 24" width="20" height="20" aria-hidden="true">
                <path fill="currentColor" d="M3 20.5V14l9-2-9-2V3.5L22 12 3 20.5Z" />
              </svg>
            </button>
          </form>
          <div className={styles.note}>{t.note}</div>
        </div>
      )}
    </>
  );
}
